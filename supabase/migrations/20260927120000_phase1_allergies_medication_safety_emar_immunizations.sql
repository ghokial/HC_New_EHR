-- Phase 1 clinical loop: structured allergies, prescribing safety checks,
-- medication administration record (eMAR), and immunizations.
-- Access follows the existing helpers: private.can_read_patient_record and
-- private.can_write_patient_record, with MFA (AAL2) for staff writes.

-- 1. Structured allergy list -------------------------------------------------
create table public.patient_allergies(
 id bigint generated by default as identity primary key,
 patient_id bigint not null references public.patients(id) on delete cascade,
 allergen_type text not null check(allergen_type in ('medication','food','environmental','other')),
 medication_id bigint references public.medications(id),
 substance text not null check(nullif(btrim(substance),'') is not null),
 reaction text,
 severity text not null default 'unknown' check(severity in ('mild','moderate','severe','life_threatening','unknown')),
 verification_status text not null default 'unconfirmed' check(verification_status in ('unconfirmed','confirmed','refuted','entered_in_error')),
 clinical_status text not null default 'active' check(clinical_status in ('active','inactive','resolved')),
 onset_date date,
 notes text,
 recorded_by uuid not null default auth.uid() references auth.users(id),
 recorded_at timestamptz not null default now(),
 updated_by uuid references auth.users(id),
 updated_at timestamptz not null default now(),
 check(allergen_type='medication' or medication_id is null)
);
create index patient_allergies_patient_idx on public.patient_allergies(patient_id,clinical_status);

create or replace function private.protect_allergy_identity() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if new.patient_id<>old.patient_id or new.recorded_by<>old.recorded_by or new.recorded_at<>old.recorded_at then
  raise exception 'Allergy patient and authorship cannot be changed';
 end if;
 new.updated_by=(select auth.uid());
 new.updated_at=now();
 return new;
end $$;
revoke all on function private.protect_allergy_identity() from public,anon,authenticated;
create trigger protect_allergy_identity before update on public.patient_allergies for each row execute function private.protect_allergy_identity();

alter table public.patient_allergies enable row level security;
create policy allergies_authorized_read on public.patient_allergies for select to authenticated using(private.can_read_patient_record(patient_id));
create policy allergies_clinical_insert on public.patient_allergies for insert to authenticated with check(private.is_aal2() and recorded_by=(select auth.uid()) and private.can_write_patient_record(patient_id,array['physician','resident','advanced_practice','nurse','pharmacist']));
create policy allergies_clinical_update on public.patient_allergies for update to authenticated using(private.is_aal2() and private.can_write_patient_record(patient_id,array['physician','resident','advanced_practice','nurse','pharmacist'])) with check(private.is_aal2() and private.can_write_patient_record(patient_id,array['physician','resident','advanced_practice','nurse','pharmacist']));
create policy mfa_required on public.patient_allergies as restrictive for all to authenticated using(private.is_aal2() or exists(select 1 from public.patient_accounts pa where pa.user_id=(select auth.uid()) and pa.patient_id=patient_allergies.patient_id) or exists(select 1 from public.patient_accounts pa join public.patient_proxies px on px.proxy_patient_id=pa.patient_id where pa.user_id=(select auth.uid()) and px.target_patient_id=patient_allergies.patient_id and px.active and px.can_view)) with check(private.is_aal2());
revoke delete on public.patient_allergies from anon,authenticated;
grant select,insert,update on public.patient_allergies to authenticated;

-- 2. Prescribing safety: allergy, interaction, and duplicate-therapy checks ---
-- Interaction alerts only fire for pairs present in public.medication_interactions;
-- no interaction content is seeded here.
alter table public.medication_orders add column if not exists safety_override_reason text;

create or replace function private.medication_safety_alerts(p_patient bigint,p_medication bigint,p_exclude_order bigint default null)
returns table(alert_type text,severity text,message text)
language sql stable security definer set search_path='' as $$
 select 'allergy'::text,a.severity,
  'Recorded '||replace(a.severity,'_','-')||' allergy to '||a.substance||coalesce(' (reaction: '||nullif(btrim(a.reaction),'')||')','')||case when a.verification_status='unconfirmed' then ' [unconfirmed]' else '' end
 from public.patient_allergies a join public.medications m on m.id=p_medication
 where a.patient_id=p_patient and a.allergen_type='medication' and a.clinical_status='active'
  and a.verification_status not in ('refuted','entered_in_error')
  and (a.medication_id=m.id or lower(btrim(a.substance)) in (lower(btrim(m.name)),lower(btrim(coalesce(m.generic_name,'')))))
 union all
 select 'interaction'::text,i.severity,
  'Interaction with active order for '||om.name||': '||i.clinical_effect||' Recommendation: '||i.recommendation
 from public.medication_orders mo
 join public.medications om on om.id=mo.medication_id
 join public.medication_interactions i on (i.medication_a_id=p_medication and i.medication_b_id=mo.medication_id) or (i.medication_b_id=p_medication and i.medication_a_id=mo.medication_id)
 where mo.patient_id=p_patient and mo.status in ('active','on_hold') and mo.id is distinct from p_exclude_order
 union all
 select 'duplicate'::text,'moderate'::text,
  'An active order for '||m.name||' already exists ('||mo.dose||coalesce(' '||mo.frequency,'')||').'
 from public.medication_orders mo join public.medications m on m.id=mo.medication_id
 where mo.patient_id=p_patient and mo.medication_id=p_medication and mo.status in ('active','on_hold') and mo.id is distinct from p_exclude_order
$$;
revoke all on function private.medication_safety_alerts(bigint,bigint,bigint) from public,anon,authenticated;

create or replace function public.medication_safety_check(target_patient bigint,target_medication bigint)
returns table(alert_type text,severity text,message text)
language plpgsql stable security definer set search_path='' as $$
begin
 if not private.is_aal2() or not private.can_read_patient_record(target_patient) then raise exception 'Authorized clinical access required'; end if;
 return query select a.alert_type,a.severity,a.message from private.medication_safety_alerts(target_patient,target_medication) a;
end $$;
revoke all on function public.medication_safety_check(bigint,bigint) from public,anon;
grant execute on function public.medication_safety_check(bigint,bigint) to authenticated;

create table public.medication_safety_overrides(
 id bigint generated by default as identity primary key,
 medication_order_id bigint not null references public.medication_orders(id) on delete cascade,
 patient_id bigint not null references public.patients(id) on delete cascade,
 alert_type text not null check(alert_type in ('allergy','interaction','duplicate')),
 severity text,
 message text not null,
 override_reason text not null,
 overridden_by uuid references auth.users(id),
 overridden_at timestamptz not null default now()
);
create index medication_safety_overrides_patient_idx on public.medication_safety_overrides(patient_id,overridden_at desc);
alter table public.medication_safety_overrides enable row level security;
create policy safety_overrides_clinical_read on public.medication_safety_overrides for select to authenticated using(private.is_aal2() and private.can_write_patient_record(patient_id,array['physician','resident','advanced_practice','nurse','pharmacist']));
revoke insert,update,delete on public.medication_safety_overrides from anon,authenticated;
grant select on public.medication_safety_overrides to authenticated;

-- The database, not the browser, blocks an unacknowledged alert.
create or replace function private.enforce_medication_safety() returns trigger language plpgsql security definer set search_path='' as $$
declare alert_count integer; summary text;
begin
 select count(*),string_agg(a.message,' | ') into alert_count,summary from private.medication_safety_alerts(new.patient_id,new.medication_id,new.id) a;
 if alert_count>0 and nullif(btrim(coalesce(new.safety_override_reason,'')),'') is null then
  raise exception 'Medication safety alert: %. An override reason is required to prescribe.',summary;
 end if;
 if alert_count=0 then new.safety_override_reason=null; end if;
 return new;
end $$;
create or replace function private.record_medication_safety_overrides() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if nullif(btrim(coalesce(new.safety_override_reason,'')),'') is not null then
  insert into public.medication_safety_overrides(medication_order_id,patient_id,alert_type,severity,message,override_reason,overridden_by)
  select new.id,new.patient_id,a.alert_type,a.severity,a.message,new.safety_override_reason,(select auth.uid())
  from private.medication_safety_alerts(new.patient_id,new.medication_id,new.id) a;
 end if;
 return new;
end $$;
revoke all on function private.enforce_medication_safety(),private.record_medication_safety_overrides() from public,anon,authenticated;
drop trigger if exists enforce_medication_safety on public.medication_orders;
create trigger enforce_medication_safety before insert on public.medication_orders for each row execute function private.enforce_medication_safety();
drop trigger if exists record_medication_safety_overrides on public.medication_orders;
create trigger record_medication_safety_overrides after insert on public.medication_orders for each row execute function private.record_medication_safety_overrides();

-- 3. Medication administration record (eMAR) ---------------------------------
-- Entries are append-only; a mistake is corrected by a new entry marked
-- entered_in_error that points at the entry it corrects.
alter table public.medication_administrations
 add column if not exists status text not null default 'given' check(status in ('given','held','refused','missed','not_available','entered_in_error')),
 add column if not exists reason text,
 add column if not exists recorded_by uuid default auth.uid() references auth.users(id),
 add column if not exists recorded_at timestamptz not null default now(),
 add column if not exists corrects_administration_id bigint references public.medication_administrations(id);
alter table public.medication_administrations add constraint medication_administrations_reason_check check(status='given' or nullif(btrim(reason),'') is not null);
alter table public.medication_administrations add constraint medication_administrations_correction_check check(status<>'entered_in_error' or corrects_administration_id is not null);
create index if not exists medication_administrations_order_idx on public.medication_administrations(medication_order_id,administered_at desc);

drop policy if exists emar_authorized_read on public.medication_administrations;
create policy emar_authorized_read on public.medication_administrations for select to authenticated using(
 exists(select 1 from public.medication_orders mo where mo.id=medication_order_id and private.can_read_patient_record(mo.patient_id))
);
drop policy if exists emar_clinical_insert on public.medication_administrations;
create policy emar_clinical_insert on public.medication_administrations for insert to authenticated with check(
 private.is_aal2() and recorded_by=(select auth.uid())
 and exists(select 1 from public.medication_orders mo where mo.id=medication_order_id and mo.status in ('active','on_hold') and private.can_write_patient_record(mo.patient_id,array['nurse','physician','resident','advanced_practice']))
);
-- A correction must point at an entry for the same order. Checked in a trigger
-- because a policy that queries its own table recurses.
create or replace function private.check_administration_correction() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if new.corrects_administration_id is not null and not exists(select 1 from public.medication_administrations prior where prior.id=new.corrects_administration_id and prior.medication_order_id=new.medication_order_id) then
  raise exception 'A correction must reference an administration for the same medication order';
 end if;
 return new;
end $$;
revoke all on function private.check_administration_correction() from public,anon,authenticated;
drop trigger if exists check_administration_correction on public.medication_administrations;
create trigger check_administration_correction before insert on public.medication_administrations for each row execute function private.check_administration_correction();
revoke update,delete on public.medication_administrations from anon,authenticated;
grant select,insert on public.medication_administrations to authenticated;

-- 4. Immunizations -------------------------------------------------------------
create table public.immunizations(
 id bigint generated by default as identity primary key,
 patient_id bigint not null references public.patients(id) on delete cascade,
 facility_id uuid references public.facilities(id),
 vaccine_name text not null check(nullif(btrim(vaccine_name),'') is not null),
 vaccine_code text,
 dose_number smallint check(dose_number is null or dose_number>0),
 lot_number text,
 expiry_date date,
 site text,
 route text check(route is null or route in ('intramuscular','subcutaneous','intradermal','oral','intranasal','other')),
 administered_at timestamptz not null,
 status text not null default 'completed' check(status in ('completed','not_done','entered_in_error')),
 not_done_reason text,
 notes text,
 recorded_by uuid not null default auth.uid() references auth.users(id),
 recorded_at timestamptz not null default now(),
 check(status<>'not_done' or nullif(btrim(not_done_reason),'') is not null)
);
create index immunizations_patient_idx on public.immunizations(patient_id,administered_at desc);

-- Only the status may change afterwards, and only to entered_in_error.
create or replace function private.protect_immunization_record() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if (to_jsonb(new)-'status')<>(to_jsonb(old)-'status') or new.status<>'entered_in_error' then
  raise exception 'Immunization records are permanent; mark the entry as entered in error and record a new one';
 end if;
 return new;
end $$;
revoke all on function private.protect_immunization_record() from public,anon,authenticated;
create trigger protect_immunization_record before update on public.immunizations for each row execute function private.protect_immunization_record();

alter table public.immunizations enable row level security;
create policy immunizations_authorized_read on public.immunizations for select to authenticated using(private.can_read_patient_record(patient_id));
create policy immunizations_clinical_insert on public.immunizations for insert to authenticated with check(private.is_aal2() and recorded_by=(select auth.uid()) and private.can_write_patient_record(patient_id,array['nurse','physician','resident','advanced_practice']) and (facility_id is null or private.is_facility_member(facility_id)));
create policy immunizations_clinical_update on public.immunizations for update to authenticated using(private.is_aal2() and private.can_write_patient_record(patient_id,array['nurse','physician','resident','advanced_practice'])) with check(private.is_aal2() and private.can_write_patient_record(patient_id,array['nurse','physician','resident','advanced_practice']));
create policy mfa_required on public.immunizations as restrictive for all to authenticated using(private.is_aal2() or exists(select 1 from public.patient_accounts pa where pa.user_id=(select auth.uid()) and pa.patient_id=immunizations.patient_id) or exists(select 1 from public.patient_accounts pa join public.patient_proxies px on px.proxy_patient_id=pa.patient_id where pa.user_id=(select auth.uid()) and px.target_patient_id=immunizations.patient_id and px.active and px.can_view)) with check(private.is_aal2());
revoke delete on public.immunizations from anon,authenticated;
grant select,insert,update on public.immunizations to authenticated;
grant usage,select on all sequences in schema public to authenticated;
