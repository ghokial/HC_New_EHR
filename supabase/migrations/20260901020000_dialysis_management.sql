-- Dialysis management derived from Dialysis_Core_Clinical.docx.
-- Configuration is editable; each session stores its setting at the time of care.
create table public.facility_dialysis_profiles (
  facility_id uuid primary key references public.facilities(id) on delete cascade,
  enabled boolean not null default false,
  center_type text check (center_type in ('freestanding_outpatient','inpatient_hospital_unit','home_therapies')),
  updated_by uuid references auth.users(id),
  updated_at timestamptz not null default now(),
  check (not enabled or center_type is not null)
);

alter table public.dialysis_sessions
  add column center_type_snapshot text check (center_type_snapshot in ('freestanding_outpatient','inpatient_hospital_unit','home_therapies')),
  add column dry_weight_kg numeric(6,2),
  add column kt_v numeric(6,3),
  add column urr_percent numeric(5,2) check (urr_percent between 0 and 100),
  add column blood_pump_speed_ml_min integer,
  add column arterial_pressure_mmhg numeric(7,2),
  add column venous_pressure_mmhg numeric(7,2);

create table public.dialysis_outpatient_chair_sessions (
  session_id bigint primary key references public.dialysis_sessions(id) on delete cascade,
  facility_id uuid not null references public.facilities(id) on delete cascade,
  chair_asset_id text not null,
  shift_code text not null check (shift_code in ('AM','PM','EVE')),
  revenue_code text not null default '0821' check (revenue_code in ('0821','0831')),
  composite_bundle_status text not null default 'OPEN' check (composite_bundle_status in ('OPEN','READY','SUBMITTED','PAID','DENIED')),
  mcp_visit_code text check (mcp_visit_code in ('90960','90961','90962'))
);

create table public.dialysis_inpatient_acute_sessions (
  session_id bigint primary key references public.dialysis_sessions(id) on delete cascade,
  facility_id uuid not null references public.facilities(id) on delete cascade,
  inpatient_admission_id uuid references public.inpatient_admissions(id),
  ms_drg_code text,
  crrt_active boolean not null default false,
  dialysate_bath_formula text,
  internal_cost_center text not null,
  revenue_code text check (revenue_code in ('0200','0820')),
  check (inpatient_admission_id is not null)
);

create table public.dialysis_home_therapy_logs (
  session_id bigint primary key references public.dialysis_sessions(id) on delete cascade,
  facility_id uuid not null references public.facilities(id) on delete cascade,
  therapy_type text not null check (therapy_type in ('HHD','CAPD','APD')),
  iot_device_serial text,
  fluid_retention_alert boolean not null default false,
  drain_failures_count integer not null default 0 check (drain_failures_count >= 0),
  training_session_count integer not null default 0 check (training_session_count >= 0),
  revenue_code text check (revenue_code in ('0825','0831')),
  supply_billing_status text not null default 'OPEN' check (supply_billing_status in ('OPEN','READY','SUBMITTED','PAID','DENIED'))
);

create table public.dialysis_device_observations (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.dialysis_sessions(id) on delete cascade,
  facility_id uuid not null references public.facilities(id) on delete cascade,
  device_serial text,
  observed_at timestamptz not null,
  flow_rate_ml_min numeric(9,2),
  blood_pump_speed_ml_min numeric(9,2),
  arterial_pressure_mmhg numeric(7,2),
  venous_pressure_mmhg numeric(7,2),
  ultrafiltration_volume_ml numeric(10,2),
  source_message_id text,
  raw_payload jsonb not null default '{}'::jsonb
);

create index dialysis_profiles_type_idx on public.facility_dialysis_profiles(center_type) where enabled;
create index dialysis_outpatient_facility_idx on public.dialysis_outpatient_chair_sessions(facility_id,shift_code);
create index dialysis_inpatient_facility_idx on public.dialysis_inpatient_acute_sessions(facility_id,inpatient_admission_id);
create index dialysis_home_facility_idx on public.dialysis_home_therapy_logs(facility_id,therapy_type);
create index dialysis_observations_session_idx on public.dialysis_device_observations(session_id,observed_at desc);

alter table public.facility_dialysis_profiles enable row level security;
alter table public.dialysis_outpatient_chair_sessions enable row level security;
alter table public.dialysis_inpatient_acute_sessions enable row level security;
alter table public.dialysis_home_therapy_logs enable row level security;
alter table public.dialysis_device_observations enable row level security;

create policy dialysis_profiles_read on public.facility_dialysis_profiles for select to authenticated using (private.is_platform_root() or private.is_facility_member(facility_id));
create policy dialysis_profiles_insert on public.facility_dialysis_profiles for insert to authenticated with check (private.is_platform_root() or private.is_facility_admin(facility_id));
create policy dialysis_profiles_update on public.facility_dialysis_profiles for update to authenticated using (private.is_platform_root() or private.is_facility_admin(facility_id)) with check (private.is_platform_root() or private.is_facility_admin(facility_id));
create policy dialysis_outpatient_access on public.dialysis_outpatient_chair_sessions for all to authenticated using (private.is_platform_root() or private.is_facility_member(facility_id)) with check (private.is_platform_root() or private.is_facility_member(facility_id));
create policy dialysis_inpatient_access on public.dialysis_inpatient_acute_sessions for all to authenticated using (private.is_platform_root() or private.is_facility_member(facility_id)) with check (private.is_platform_root() or private.is_facility_member(facility_id));
create policy dialysis_home_access on public.dialysis_home_therapy_logs for all to authenticated using (private.is_platform_root() or private.is_facility_member(facility_id)) with check (private.is_platform_root() or private.is_facility_member(facility_id));
create policy dialysis_observations_access on public.dialysis_device_observations for all to authenticated using (private.is_platform_root() or private.is_facility_member(facility_id)) with check (private.is_platform_root() or private.is_facility_member(facility_id));

revoke all on public.facility_dialysis_profiles, public.dialysis_outpatient_chair_sessions, public.dialysis_inpatient_acute_sessions, public.dialysis_home_therapy_logs, public.dialysis_device_observations from anon, authenticated;
grant select,insert,update on public.facility_dialysis_profiles to authenticated;
grant select,insert,update,delete on public.dialysis_outpatient_chair_sessions, public.dialysis_inpatient_acute_sessions, public.dialysis_home_therapy_logs, public.dialysis_device_observations to authenticated;
grant usage,select on sequence public.dialysis_device_observations_id_seq to authenticated;
