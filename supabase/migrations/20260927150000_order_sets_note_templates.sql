-- Phase 1: facility-managed order sets and note templates.
-- No clinical content is seeded; each facility (or platform Root) authors its own.

create table public.note_templates(
 id bigint generated by default as identity primary key,
 facility_id uuid references public.facilities(id) on delete cascade,
 name text not null check(nullif(btrim(name),'') is not null),
 note_type text not null,
 body text not null,
 active boolean not null default true,
 created_by uuid not null default auth.uid() references auth.users(id),
 created_at timestamptz not null default now(),
 unique nulls not distinct (facility_id,name)
);

create table public.order_sets(
 id bigint generated by default as identity primary key,
 facility_id uuid references public.facilities(id) on delete cascade,
 name text not null check(nullif(btrim(name),'') is not null),
 description text,
 active boolean not null default true,
 created_by uuid not null default auth.uid() references auth.users(id),
 created_at timestamptz not null default now(),
 unique nulls not distinct (facility_id,name)
);
create table public.order_set_items(
 order_set_id bigint not null references public.order_sets(id) on delete cascade,
 catalog_id bigint not null references public.clinical_order_catalog(id),
 priority text not null default 'Routine' check(priority in ('Routine','Urgent','STAT')),
 primary key(order_set_id,catalog_id)
);

-- Platform-wide content (facility_id null) is managed by Root; facility content by that facility's administrators.
create or replace function private.can_manage_clinical_content(fid uuid) returns boolean language sql stable security invoker set search_path='' as $$
 select private.is_platform_root() or (fid is not null and private.is_facility_admin(fid))
$$;
revoke all on function private.can_manage_clinical_content(uuid) from public,anon;
grant execute on function private.can_manage_clinical_content(uuid) to authenticated;

alter table public.note_templates enable row level security;
alter table public.order_sets enable row level security;
alter table public.order_set_items enable row level security;
create policy note_templates_read on public.note_templates for select to authenticated using(private.is_aal2() and (facility_id is null or private.is_platform_root() or private.is_facility_member(facility_id)));
create policy note_templates_manage on public.note_templates for all to authenticated using(private.is_aal2() and private.can_manage_clinical_content(facility_id)) with check(private.is_aal2() and private.can_manage_clinical_content(facility_id));
create policy order_sets_read on public.order_sets for select to authenticated using(private.is_aal2() and (facility_id is null or private.is_platform_root() or private.is_facility_member(facility_id)));
create policy order_sets_manage on public.order_sets for all to authenticated using(private.is_aal2() and private.can_manage_clinical_content(facility_id)) with check(private.is_aal2() and private.can_manage_clinical_content(facility_id));
create policy order_set_items_read on public.order_set_items for select to authenticated using(exists(select 1 from public.order_sets s where s.id=order_set_id));
create policy order_set_items_manage on public.order_set_items for all to authenticated
 using(exists(select 1 from public.order_sets s where s.id=order_set_id and private.is_aal2() and private.can_manage_clinical_content(s.facility_id)))
 with check(exists(select 1 from public.order_sets s where s.id=order_set_id and private.is_aal2() and private.can_manage_clinical_content(s.facility_id)));
grant select,insert,update,delete on public.note_templates,public.order_sets,public.order_set_items to authenticated;
grant usage,select on all sequences in schema public to authenticated;
create index note_templates_facility_idx on public.note_templates(facility_id) where active;
create index order_sets_facility_idx on public.order_sets(facility_id) where active;
