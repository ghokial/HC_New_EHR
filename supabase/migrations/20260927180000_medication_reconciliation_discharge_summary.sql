-- Phase 2: medication reconciliation (Patient_admission.docx: "reconciles medications")
-- and a signed discharge summary for each inpatient stay.

create table public.inpatient_medication_reconciliations(
 id bigint generated by default as identity primary key,
 facility_id uuid not null references public.facilities(id),
 admission_id uuid not null references public.inpatient_admissions(id) on delete cascade,
 patient_id bigint not null references public.patients(id),
 stage text not null check(stage in ('admission','discharge')),
 medication_order_id bigint references public.medication_orders(id),
 home_medication text,
 decision text not null check(decision in ('continue','modify','hold','stop')),
 decision_note text,
 reconciled_by uuid not null default auth.uid() references auth.users(id),
 reconciled_at timestamptz not null default now(),
 check(medication_order_id is not null or nullif(btrim(home_medication),'') is not null),
 check(decision not in ('modify','hold','stop') or nullif(btrim(decision_note),'') is not null)
);
create unique index medication_reconciliation_once on public.inpatient_medication_reconciliations(admission_id,stage,medication_order_id) where medication_order_id is not null;
create index medication_reconciliation_admission_idx on public.inpatient_medication_reconciliations(admission_id,stage);

create table public.inpatient_discharge_summaries(
 id uuid primary key default gen_random_uuid(),
 facility_id uuid not null references public.facilities(id),
 admission_id uuid not null unique references public.inpatient_admissions(id) on delete cascade,
 patient_id bigint not null references public.patients(id),
 hospital_course text,
 discharge_diagnosis text,
 condition_at_discharge text,
 discharge_disposition text check(discharge_disposition in ('home','home_with_services','transfer_facility','against_medical_advice','deceased','other')),
 follow_up_instructions text,
 patient_instructions text,
 status text not null default 'draft' check(status in ('draft','signed')),
 author_user_id uuid not null default auth.uid() references auth.users(id),
 signed_by uuid references auth.users(id),
 signed_at timestamptz,
 updated_at timestamptz not null default now()
);

create or replace function private.can_prescribe_at(fid uuid) returns boolean language sql stable security invoker set search_path='' as $$
 select private.is_platform_root() or private.has_facility_role(fid,array['physician','resident','advanced_practice','pharmacist'])
$$;
revoke all on function private.can_prescribe_at(uuid) from public,anon;
grant execute on function private.can_prescribe_at(uuid) to authenticated;

-- Records one reconciliation decision. Stopping a medication at discharge also
-- completes its order, so the discharge medication list is accurate.
create or replace function public.reconcile_inpatient_medication(target_admission uuid,reconciliation_stage text,target_order bigint,reconciliation_decision text,note text default null,home_medication_name text default null)
returns bigint language plpgsql security invoker set search_path='' as $$
declare adm public.inpatient_admissions%rowtype; result bigint;
begin
 select * into adm from public.inpatient_admissions where id=target_admission;
 if adm.id is null or not private.can_prescribe_at(adm.facility_id) then raise exception 'Only prescribers or pharmacists at this facility can reconcile medications'; end if;
 if adm.admission_status<>'admitted' then raise exception 'Medications are reconciled while the patient is admitted'; end if;
 if target_order is not null and not exists(select 1 from public.medication_orders mo where mo.id=target_order and mo.patient_id=adm.patient_id) then raise exception 'That medication order does not belong to this patient'; end if;
 insert into public.inpatient_medication_reconciliations(facility_id,admission_id,patient_id,stage,medication_order_id,home_medication,decision,decision_note)
 values(adm.facility_id,adm.id,adm.patient_id,reconciliation_stage,target_order,nullif(btrim(coalesce(home_medication_name,'')),''),reconciliation_decision,nullif(btrim(coalesce(note,'')),''))
 on conflict (admission_id,stage,medication_order_id) where medication_order_id is not null
 do update set decision=excluded.decision,decision_note=excluded.decision_note,reconciled_by=(select auth.uid()),reconciled_at=now()
 returning id into result;
 if reconciliation_stage='discharge' and reconciliation_decision='stop' and target_order is not null then
  update public.medication_orders set status='completed',end_at=coalesce(end_at,now()) where id=target_order and status in ('active','on_hold');
 end if;
 return result;
end $$;
revoke all on function public.reconcile_inpatient_medication(uuid,text,bigint,text,text,text) from public,anon;
grant execute on function public.reconcile_inpatient_medication(uuid,text,bigint,text,text,text) to authenticated;

-- Active medication orders still waiting for a discharge decision.
create or replace function public.pending_discharge_reconciliation(target_admission uuid) returns table(medication_order_id bigint,medication_name text,dose text,frequency text)
language sql stable security invoker set search_path='' as $$
 select mo.id,m.name,mo.dose,mo.frequency from public.inpatient_admissions a
 join public.medication_orders mo on mo.patient_id=a.patient_id and mo.status in ('active','on_hold')
 join public.medications m on m.id=mo.medication_id
 where a.id=target_admission
  and not exists(select 1 from public.inpatient_medication_reconciliations r where r.admission_id=a.id and r.stage='discharge' and r.medication_order_id=mo.id)
 order by m.name
$$;
revoke all on function public.pending_discharge_reconciliation(uuid) from public,anon;
grant execute on function public.pending_discharge_reconciliation(uuid) to authenticated;

-- Discharge now requires every active medication to have a discharge decision.
create or replace function public.discharge_inpatient(target_admission uuid, discharge_time timestamptz default now()) returns void language plpgsql security invoker set search_path='' as $$
declare adm public.inpatient_admissions%rowtype; target_bed uuid; acct uuid; pending text;
begin
 select * into adm from public.inpatient_admissions where id=target_admission;
 if adm.id is null or not private.can_manage_inpatient(adm.facility_id) then raise exception 'Admission not found or not authorized'; end if;
 if adm.admission_status<>'admitted' then raise exception 'This admission is already %',adm.admission_status; end if;
 select string_agg(p.medication_name,', ') into pending from public.pending_discharge_reconciliation(target_admission) p;
 if pending is not null then raise exception 'Reconcile these medications before discharge: %',pending; end if;
 select bed_id into target_bed from public.inpatient_bed_assignments where admission_id=target_admission and released_at is null and assignment_status in ('reserved','active') limit 1;
 update public.inpatient_admissions set admission_status='discharged',discharge_ordered_at=coalesce(discharge_ordered_at,discharge_time),discharged_at=discharge_time,updated_at=now() where id=target_admission;
 update public.encounters set status='closed',end_at=discharge_time where id=adm.encounter_id;
 update public.inpatient_bed_assignments set assignment_status='released',released_at=discharge_time,release_reason='discharge' where admission_id=target_admission and released_at is null;
 if target_bed is not null then update public.inpatient_beds set operational_status='needs_cleaning',updated_at=now() where id=target_bed; end if;
 select id into acct from public.inpatient_accounts where admission_id=target_admission and status='active';
 if acct is not null then perform public.post_inpatient_room_charges(acct); end if;
 update public.inpatient_accounts set status='ready_to_claim',service_period_end=discharge_time::date where admission_id=target_admission and status='active';
end $$;

-- Discharge summary: clinicians draft; physicians, residents, or advanced practice sign;
-- a signed summary is final.
create or replace function private.guard_discharge_summary() returns trigger language plpgsql security definer set search_path='' as $$
declare adm public.inpatient_admissions%rowtype;
begin
 select * into adm from public.inpatient_admissions where id=new.admission_id;
 if adm.id is null then raise exception 'Admission not found'; end if;
 new.facility_id:=adm.facility_id; new.patient_id:=adm.patient_id; new.updated_at:=now();
 if tg_op='UPDATE' then
  if old.status='signed' then raise exception 'A signed discharge summary cannot be changed; add a clinical note as an addendum'; end if;
  if new.admission_id<>old.admission_id or new.author_user_id<>old.author_user_id then raise exception 'Summary admission and author cannot be changed'; end if;
 end if;
 if new.status='signed' then
  if not (private.is_platform_root() or private.has_facility_role(adm.facility_id,array['physician','resident','advanced_practice'])) then raise exception 'Only a physician, resident, or advanced practice clinician can sign the discharge summary'; end if;
  if nullif(btrim(coalesce(new.hospital_course,'')),'') is null or nullif(btrim(coalesce(new.discharge_diagnosis,'')),'') is null or new.discharge_disposition is null or nullif(btrim(coalesce(new.follow_up_instructions,'')),'') is null then
   raise exception 'Hospital course, discharge diagnosis, disposition, and follow-up instructions are required to sign';
  end if;
  new.signed_by:=(select auth.uid()); new.signed_at:=now();
 else new.signed_by:=null; new.signed_at:=null;
 end if;
 return new;
end $$;
revoke all on function private.guard_discharge_summary() from public,anon,authenticated;
create trigger guard_discharge_summary before insert or update on public.inpatient_discharge_summaries for each row execute function private.guard_discharge_summary();

alter table public.inpatient_medication_reconciliations enable row level security;
alter table public.inpatient_discharge_summaries enable row level security;
create policy reconciliation_read on public.inpatient_medication_reconciliations for select to authenticated using(private.is_aal2() and private.can_manage_inpatient(facility_id) or private.is_aal2() and private.can_prescribe_at(facility_id));
create policy reconciliation_insert on public.inpatient_medication_reconciliations for insert to authenticated with check(private.is_aal2() and reconciled_by=(select auth.uid()) and private.can_prescribe_at(facility_id));
create policy reconciliation_update on public.inpatient_medication_reconciliations for update to authenticated using(private.is_aal2() and private.can_prescribe_at(facility_id)) with check(private.is_aal2() and private.can_prescribe_at(facility_id));
revoke delete on public.inpatient_medication_reconciliations from anon,authenticated;

create policy discharge_summary_staff_read on public.inpatient_discharge_summaries for select to authenticated using(private.is_aal2() and private.can_manage_inpatient(facility_id));
-- Patients (and their authorized proxies) read their own signed summaries without MFA, like the rest of the portal.
create policy discharge_summary_patient_read on public.inpatient_discharge_summaries for select to authenticated using(status='signed' and (
 exists(select 1 from public.patient_accounts pa where pa.user_id=(select auth.uid()) and pa.patient_id=inpatient_discharge_summaries.patient_id)
 or exists(select 1 from public.patient_accounts pa join public.patient_proxies px on px.proxy_patient_id=pa.patient_id where pa.user_id=(select auth.uid()) and px.target_patient_id=inpatient_discharge_summaries.patient_id and px.active and px.can_view)));
create policy discharge_summary_write on public.inpatient_discharge_summaries for insert to authenticated with check(private.is_aal2() and author_user_id=(select auth.uid()) and exists(select 1 from public.inpatient_admissions a where a.id=admission_id and private.has_facility_role(a.facility_id,array['physician','resident','advanced_practice','nurse'])));
create policy discharge_summary_update on public.inpatient_discharge_summaries for update to authenticated using(private.is_aal2() and private.has_facility_role(facility_id,array['physician','resident','advanced_practice','nurse'])) with check(private.is_aal2() and private.has_facility_role(facility_id,array['physician','resident','advanced_practice','nurse']));
revoke delete on public.inpatient_discharge_summaries from anon,authenticated;
grant select,insert,update on public.inpatient_medication_reconciliations,public.inpatient_discharge_summaries to authenticated;

do $$ declare t text; begin
 foreach t in array array['inpatient_medication_reconciliations','inpatient_discharge_summaries'] loop
  execute format('create trigger audit_row_change after insert or update or delete on public.%I for each row execute function private.audit_row_change()',t);
 end loop;
end $$;
