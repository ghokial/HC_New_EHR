-- Phase 3: HL7 v2 laboratory interfaces. A facility registers a lab interface and
-- receives a secret key once. Results arriving over HL7 are matched to the order
-- and the patient, stored as "pending validation", and never released until a
-- laboratory supervisor validates them in Healthcarology, as for manual results.

create table public.lab_interfaces(
 id uuid primary key default gen_random_uuid(),
 facility_id uuid not null references public.facilities(id) on delete cascade,
 name text not null check(nullif(btrim(name),'') is not null),
 key_hash text not null unique,
 active boolean not null default true,
 created_by uuid not null default auth.uid() references auth.users(id),
 created_at timestamptz not null default now(),
 last_message_at timestamptz,
 unique(facility_id,name)
);
create table public.hl7_messages(
 id bigint generated by default as identity primary key,
 interface_id uuid not null references public.lab_interfaces(id) on delete cascade,
 facility_id uuid not null references public.facilities(id) on delete cascade,
 control_id text not null,
 message_type text not null,
 direction text not null default 'inbound' check(direction in ('inbound','outbound')),
 status text not null check(status in ('accepted','rejected')),
 error text,
 results_created integer not null default 0,
 raw_message text not null,
 received_at timestamptz not null default now(),
 unique(interface_id,direction,control_id)
);

create or replace function private.can_manage_lab_interfaces(fid uuid) returns boolean language sql stable security invoker set search_path='' as $$
 select private.is_platform_root() or private.is_facility_admin(fid) or private.has_facility_role(fid,array['lab_supervisor'])
$$;
revoke all on function private.can_manage_lab_interfaces(uuid) from public,anon;
grant execute on function private.can_manage_lab_interfaces(uuid) to authenticated;

alter table public.lab_interfaces enable row level security;
alter table public.hl7_messages enable row level security;
create policy lab_interfaces_read on public.lab_interfaces for select to authenticated using(private.is_aal2() and private.can_manage_lab_interfaces(facility_id));
create policy lab_interfaces_update on public.lab_interfaces for update to authenticated using(private.is_aal2() and private.can_manage_lab_interfaces(facility_id)) with check(private.is_aal2() and private.can_manage_lab_interfaces(facility_id));
create policy hl7_messages_read on public.hl7_messages for select to authenticated using(private.is_aal2() and (private.can_manage_lab_interfaces(facility_id) or private.has_facility_role(facility_id,array['lab_tech'])));
revoke insert,delete on public.lab_interfaces from anon,authenticated;
revoke insert,update,delete on public.hl7_messages from anon,authenticated;
-- The key hash is never readable: users get every column except key_hash, and may only
-- rename or deactivate an interface.
revoke select,update on public.lab_interfaces from anon,authenticated;
grant select(id,facility_id,name,active,created_by,created_at,last_message_at) on public.lab_interfaces to authenticated;
grant update(name,active) on public.lab_interfaces to authenticated;
grant select on public.hl7_messages to authenticated;

-- Creates an interface and returns its secret key once; only the hash is stored.
create or replace function public.create_lab_interface(target_facility uuid,interface_name text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare secret text; created uuid;
begin
 if not private.is_aal2() or not private.can_manage_lab_interfaces(target_facility) then raise exception 'Only facility administrators or laboratory supervisors can register lab interfaces'; end if;
 secret:='hcl_'||encode(extensions.gen_random_bytes(32),'hex');
 insert into public.lab_interfaces(facility_id,name,key_hash,created_by) values(target_facility,btrim(interface_name),encode(extensions.digest(secret,'sha256'),'hex'),(select auth.uid())) returning id into created;
 return jsonb_build_object('interface_id',created,'secret_key',secret);
end $$;
revoke all on function public.create_lab_interface(uuid,text) from public,anon;
grant execute on function public.create_lab_interface(uuid,text) to authenticated;

-- Ingests parsed ORU^R01 results. Called only by the hl7-lab Edge Function with the
-- service role, after it has checked the interface key. Returns the ACK decision.
-- payload: {controlId, messageType, patientIdentifiers:[{value,type}], orders:[{placerOrderId, observations:[...]}]}
create or replace function public.hl7_ingest_lab_results(target_interface uuid,payload jsonb,raw_message text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare iface public.lab_interfaces%rowtype; prior public.hl7_messages%rowtype; o jsonb; x jsonb; lab public.lab_orders%rowtype; ord public.orders%rowtype;
 pat public.patients%rowtype; created integer:=0; problem text; control text:=payload->>'controlId';
begin
 select * into iface from public.lab_interfaces where id=target_interface and active;
 if iface.id is null then return jsonb_build_object('ack','AR','error','Unknown or inactive interface'); end if;
 select * into prior from public.hl7_messages where interface_id=iface.id and direction='inbound' and control_id=control;
 if prior.id is not null then
  return jsonb_build_object('ack',case when prior.status='accepted' then 'AA' else 'AE' end,'error',prior.error,'duplicate',true,'results_created',0);
 end if;
 begin
  for o in select * from jsonb_array_elements(coalesce(payload->'orders','[]'::jsonb)) loop
   select * into lab from public.lab_orders where id=nullif(o->>'placerOrderId','')::bigint;
   if lab.id is null then problem:='Order '||coalesce(o->>'placerOrderId','?')||' was not found'; raise exception using message=problem; end if;
   select * into ord from public.orders where id=lab.order_id;
   select * into pat from public.patients where id=ord.patient_id;
   if pat.facility_id is distinct from iface.facility_id then problem:='Order '||lab.id||' does not belong to this facility'; raise exception using message=problem; end if;
   -- Wrong-patient protection: PID-3 must carry the UNIN or this facility's MRN of the ordered patient.
   if not exists(select 1 from jsonb_array_elements(payload->'patientIdentifiers') i
                 where (pat.snau is not null and i->>'value'=pat.snau)
                    or exists(select 1 from public.facility_patient_mrns m where m.facility_id=iface.facility_id and m.patient_id=pat.id and m.mrn=i->>'value')) then
    problem:='Patient identifiers in PID-3 do not match the patient on order '||lab.id; raise exception using message=problem;
   end if;
   for x in select * from jsonb_array_elements(coalesce(o->'observations','[]'::jsonb)) loop
    if x->>'status'='cancelled' then continue; end if;
    insert into public.lab_results(lab_order_id,result_at,result_status,analyte_code,value,numeric_value,units,reference_range,abnormal_flag,interpretation,validation_status,validation_note)
    values(lab.id,coalesce(nullif(x->>'observedAt','')::timestamptz,now()),x->>'status',coalesce(nullif(x->>'code',''),lab.test_code),x->>'value',nullif(x->>'numericValue','')::numeric,
           nullif(x->>'units',''),nullif(x->>'referenceRange',''),nullif(x->>'abnormalFlag',''),nullif(x->>'interpretation',''),'pending_validation','Received by HL7 interface '||iface.name);
    created:=created+1;
   end loop;
   update public.orders set status='in_progress',updated_at=now() where id=ord.id and status='pending';
  end loop;
  insert into public.hl7_messages(interface_id,facility_id,control_id,message_type,status,results_created,raw_message)
  values(iface.id,iface.facility_id,control,coalesce(payload->>'messageType','ORU^R01'),'accepted',created,raw_message);
  update public.lab_interfaces set last_message_at=now() where id=iface.id;
  return jsonb_build_object('ack','AA','results_created',created);
 exception when others then
  insert into public.hl7_messages(interface_id,facility_id,control_id,message_type,status,error,raw_message)
  values(iface.id,iface.facility_id,control,coalesce(payload->>'messageType','ORU^R01'),'rejected',sqlerrm,raw_message);
  return jsonb_build_object('ack','AE','error',sqlerrm,'results_created',0);
 end;
end $$;
revoke all on function public.hl7_ingest_lab_results(uuid,jsonb,text) from public,anon,authenticated;
grant execute on function public.hl7_ingest_lab_results(uuid,jsonb,text) to service_role;

-- Pending lab orders for an interface, with what an ORM^O01 needs.
create or replace function public.hl7_pending_lab_orders(target_interface uuid) returns table(lab_order_id bigint,test_code text,priority text,created_at timestamptz,first_name text,middle_name text,last_name text,sex text,date_of_birth date,snau text,mrn text,facility_name text)
language sql stable security definer set search_path='' as $$
 select lo.id,lo.test_code,lo.priority,o.created_at,p.first_name,p.middle_name,p.last_name,p.sex,p.date_of_birth,p.snau,m.mrn,f.name
 from public.lab_interfaces i
 join public.patients p on p.facility_id=i.facility_id
 join public.orders o on o.patient_id=p.id and o.order_type='lab' and o.status='pending'
 join public.lab_orders lo on lo.order_id=o.id
 join public.facilities f on f.id=i.facility_id
 left join public.facility_patient_mrns m on m.facility_id=i.facility_id and m.patient_id=p.id
 where i.id=target_interface and i.active
 order by o.created_at
$$;
revoke all on function public.hl7_pending_lab_orders(uuid) from public,anon,authenticated;
grant execute on function public.hl7_pending_lab_orders(uuid) to service_role;
