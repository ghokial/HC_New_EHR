-- Healthcarology identifiers are immutable internal identifiers. National issuing
-- authority adapters may replace the generator only after country-specific approval.
create or replace function private.assign_healthcarology_unin() returns trigger language plpgsql security definer set search_path='' as $$
begin
  if new.snau is null or btrim(new.snau)='' then new.snau := 'HC-' || upper(replace(gen_random_uuid()::text,'-','')); end if;
  return new;
end $$;
create or replace function private.prevent_unin_change() returns trigger language plpgsql security definer set search_path='' as $$
begin
  if old.snau is distinct from new.snau then raise exception 'UNIN is permanent and cannot be changed'; end if;
  return new;
end $$;
revoke all on function private.assign_healthcarology_unin(),private.prevent_unin_change() from public,anon,authenticated;
drop trigger if exists assign_patient_unin on public.patients;
create trigger assign_patient_unin before insert on public.patients for each row execute function private.assign_healthcarology_unin();
drop trigger if exists prevent_patient_unin_change on public.patients;
create trigger prevent_patient_unin_change before update of snau on public.patients for each row execute function private.prevent_unin_change();
update public.patients set snau='HC-' || upper(replace(gen_random_uuid()::text,'-','')) where snau is null;
alter table public.patients alter column snau set not null;

