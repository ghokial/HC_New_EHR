create or replace function private.interpret_lab_result() returns trigger language plpgsql security definer set search_path='' as $$
declare r public.lab_reference_ranges%rowtype;
begin
  if new.reference_range_id is null or new.numeric_value is null then return new; end if;
  select * into r from public.lab_reference_ranges where id=new.reference_range_id;
  new.reference_range=concat_ws(' - ',r.normal_low,r.normal_high);
  new.units=r.units;
  new.interpretation=case when (r.critical_low is not null and new.numeric_value<r.critical_low) or (r.critical_high is not null and new.numeric_value>r.critical_high) then 'dangerously_abnormal' when (r.normal_low is not null and new.numeric_value<r.normal_low) or (r.normal_high is not null and new.numeric_value>r.normal_high) then 'out_of_range' else 'normal' end;
  new.abnormal_flag=case new.interpretation when 'normal' then 'N' when 'out_of_range' then 'A' else 'C' end;
  return new;
end $$;
revoke all on function private.interpret_lab_result() from public,anon,authenticated;
create trigger interpret_lab_result before insert or update of numeric_value,reference_range_id on public.lab_results for each row execute function private.interpret_lab_result();

