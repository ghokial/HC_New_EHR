import fs from "node:fs/promises";
import path from "node:path";
import { FileBlob, SpreadsheetFile } from "file:///C:/Users/ghoki/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/@oai/artifact-tool/dist/artifact_tool.mjs";

const sourceDirectory = "C:/Users/ghoki/OneDrive/Desktop/Removable 2020/HealthCarology/New_HC_platform";
const migrationPath = process.argv[2];
if (!migrationPath) throw new Error("Migration path is required.");

const sources = [
  "anatomic_pathology_examens_reference_ranges.xlsx",
  "blood_bank_examens_reference_ranges.xlsx",
  "blood_bank_transfusion_services_reference_ranges.xlsx",
  "chemistry_lab_examens_reference_ranges.xlsx",
  "clinical_laboratory_examens_reference_ranges.xlsx",
  "complete_cytology_billing_codes.xlsx",
  "core_lab_examens_reference_ranges.xlsx",
  "genetic_testing_billing_codes.xlsx",
];

const normalized = value => String(value ?? "").trim().toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
const sql = value => value == null || value === "" ? "null" : `'${String(value).replaceAll("'", "''")}'`;
const pick = (row, headers, matches) => {
  const index = headers.findIndex(header => matches.some(match => header.includes(match)));
  return index < 0 ? null : String(row[index] ?? "").trim() || null;
};

const records = [];
for (const source of sources) {
  const workbook = await SpreadsheetFile.importXlsx(await FileBlob.load(path.join(sourceDirectory, source)));
  for (const sheet of workbook.worksheets.items) {
    const values = sheet.getUsedRange(true)?.values ?? [];
    if (values.length < 2) continue;
    const headers = values[0].map(normalized);
    for (let index = 1; index < values.length; index += 1) {
      const row = values[index];
      const cptCode = pick(row, headers, ["cpt code"]);
      const examName = pick(row, headers, ["examen name", "examen test name", "examination description", "examination examen", "examen"]);
      if (!cptCode || !examName) continue;
      const billingCode = cptCode.match(/^\d{5}/)?.[0] ?? null;
      if (!billingCode) throw new Error(`No five-digit billing code at ${source} ${sheet.name} row ${index + 1}`);
      records.push({
        cptCode,
        billingCode,
        examName,
        category: pick(row, headers, ["category"]),
        specimen: pick(row, headers, ["specimen"]),
        referenceText: pick(row, headers, ["reference range", "reference value range", "result interpretation", "target output", "diagnostic target"]),
        source,
        sheet: sheet.name,
        row: index + 1,
      });
    }
  }
}

const values = records.map(record => `(${sql(record.cptCode)},${sql(record.billingCode)},${sql(record.examName)},${sql(record.category)},${sql(record.specimen)},${sql(record.referenceText)},${sql(record.source)},${sql(record.sheet)},${record.row})`).join(",\n");
const migration = `create table public.laboratory_exam_catalog(
  id bigint generated by default as identity primary key,
  cpt_code text not null,
  billing_code text not null check(billing_code ~ '^[0-9]{5}$'),
  exam_name text not null,
  category text,
  specimen_requirement text,
  reference_range_text text,
  source_workbook text not null,
  source_sheet text not null,
  source_row integer not null check(source_row>=2),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(source_workbook,source_sheet,source_row)
);

alter table public.laboratory_exam_catalog enable row level security;
create policy laboratory_exam_catalog_read on public.laboratory_exam_catalog for select to authenticated using(active);
grant select on public.laboratory_exam_catalog to authenticated;

alter table public.facility_chargemaster_items
  add column laboratory_exam_catalog_id bigint references public.laboratory_exam_catalog(id);
create unique index facility_chargemaster_laboratory_exam_idx
  on public.facility_chargemaster_items(facility_id,laboratory_exam_catalog_id)
  where laboratory_exam_catalog_id is not null;

insert into public.laboratory_exam_catalog(cpt_code,billing_code,exam_name,category,specimen_requirement,reference_range_text,source_workbook,source_sheet,source_row) values
${values}
on conflict(source_workbook,source_sheet,source_row) do update set
  cpt_code=excluded.cpt_code,
  billing_code=excluded.billing_code,
  exam_name=excluded.exam_name,
  category=excluded.category,
  specimen_requirement=excluded.specimen_requirement,
  reference_range_text=excluded.reference_range_text,
  active=true;

insert into public.clinical_order_catalog(order_type,code,name,use_text,reference_guidance,source_url)
select distinct on (billing_code)
  'lab',billing_code,exam_name,
  coalesce('Specimen requirement: '||specimen_requirement,'Specimen requirement not supplied in the workbook.'),
  coalesce(reference_range_text,'No reference or interpretation text was supplied in the workbook.'),
  null
from public.laboratory_exam_catalog
where active
order by billing_code,source_workbook,source_sheet,source_row
on conflict(order_type,code) do update set
  name=excluded.name,
  use_text=excluded.use_text,
  reference_guidance=excluded.reference_guidance,
  active=true;

create index laboratory_exam_catalog_cpt_idx on public.laboratory_exam_catalog(billing_code);
create index laboratory_exam_catalog_name_idx on public.laboratory_exam_catalog(exam_name);
`;

await fs.writeFile(migrationPath, migration, "utf8");
console.log(JSON.stringify({ sourceRows: records.length, distinctBillingCodes: new Set(records.map(record => record.billingCode)).size, migrationPath }));
